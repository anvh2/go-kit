package generator

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestExampleIsUpToDate(t *testing.T) {
	dir := filepath.Join("..", "internal", "example")
	src, err := os.ReadFile(filepath.Join(dir, "models.go"))
	if err != nil {
		t.Fatal(err)
	}
	got, err := Generate("models.go", src)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(filepath.Join(dir, "autogenerated_models.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("internal/example/autogenerated_models.gen.go is stale: run go generate ./cmd/goqueryset/...")
	}
}

func TestErrors(t *testing.T) {
	cases := map[string]struct{ src, want string }{
		"no marker":  {"package p\ntype A struct{ ID int }\n", "no struct is marked"},
		"not struct": {"package p\n// gen:qs\ntype A int\n", "is not a struct"},
		"generic":    {"package p\n// gen:qs\ntype A[T any] struct{ ID T }\n", "generic structs"},
		"no columns": {"package p\n// gen:qs\ntype A struct{ B []int }\n", "no column fields"},
		"bad import": {"package p\nimport x \"example.com/y\"\n// gen:qs\ntype A struct{ ID z.T }\n", `package "z"`},
	}
	for name, c := range cases {
		_, err := Generate("p.go", []byte(c.src))
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: err = %v, want containing %q", name, err, c.want)
		}
	}
}

func TestImportsAndColumns(t *testing.T) {
	src := `package p

import (
	"time"
	dt "gorm.io/datatypes"
	"github.com/google/uuid"
	"gopkg.in/yaml.v3"
)

// gen:qs
type A struct {
	ID      uuid.UUID
	Meta    dt.JSON
	Doc     yaml.Node
	At      time.Time
	HTTPURL string
	ExplicitName string ` + "`gorm:\"column:name\"`" + `
}
`
	out, err := Generate("p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`"time"`, `dt "gorm.io/datatypes"`, `"github.com/google/uuid"`, `"gopkg.in/yaml.v3"`, `ADBSchemaField("http_url")`, `ADBSchemaField("name")`, `func (qs AQuerySet) AtGt(`} {
		if !bytes.Contains(out, []byte(want)) {
			t.Errorf("generated code lacks %s", want)
		}
	}
	if bytes.Contains(out, []byte("func (qs AQuerySet) MetaGt(")) {
		t.Error("an opaque type must not get comparison methods")
	}
}
