// Generate returns the query set source for the structs of src (a Go file named filename) annotated with a
// "gen:qs" comment line. The output belongs to the same package and is gofmt-formatted.
func Generate(filename string, src []byte) ([]byte, error) {
	f, err := parse(filename, src)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, f); err != nil {
		return nil, err
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return out, nil
}

